#!/usr/bin/env python3
"""Warm vs cold on a real project: does mcp-rector-warm give the same answers as a
fresh `rector process`?

    tools/warm-vs-cold.py --project DIR --files 'src/**/*.php' --out OUT [options]

Warm side: ONE mcp-rector-warm session over stdio, driven by the official Python MCP
client (as tests/E2E does), calling rector_process with dryRun: true on each file in
order. Cold side: a fresh `rector process --dry-run` per file, --jobs at a time. Both
sides use the flags RectorTool::process() passes, and a generated wrapper config that
`require`s --config exactly once and points Rector's cache at a scratch directory (one
for warm, one per cold process), so the project's own cache is neither written nor
able to mask a difference.

Every call is a dry run. Nothing in this script can apply a change.

Modes (the report labels which one ran):
  checkout        this checkout's bin/ and vendor/ (vendor/bin/rector for cold).
  project-vendor  --project-autoload PATH: emulate a project-dependency install --
                  this checkout's bin/ and src/ on top of the project's own Composer
                  autoloader, and the rector next to that autoloader for cold. This is
                  how a project that has the package in require-dev runs it.

Writes to --out: report.json, report.md, files.txt, warm-server.stderr, the wrapper
config, the Rector caches, and (project-vendor) the shim.
Exit status: 0 all match, 1 at least one mismatch, 2 no mismatch but a side errored.
"""

